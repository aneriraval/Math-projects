#The Count Five Test:
import numpy as np
import matplotlib.pyplot as plt

def count5(x, y):
    X, Y = x - x.mean(), y - y.mean()
    outx = np.sum(X > Y.max()) + np.sum(X < Y.min())
    outy = np.sum(Y > X.max()) + np.sum(Y < X.min())
    return max(outx, outy)

n1, n2, m = 15, 18, 10000
T_obs = 12

null_stats = np.empty(m, dtype=int)
for j in range(m):
    x = np.random.normal(0, 1, n1)
    y = np.random.normal(0, 1, n2)
    null_stats[j] = count5(x, y)

# --- plot ---
bins = np.arange(null_stats.min(), null_stats.max() + 2) - 0.5
weights = np.ones_like(null_stats) / m

fig, ax = plt.subplots(figsize=(7, 5))
ax.hist(null_stats, bins=bins, weights=weights, color="blue", edgecolor="white")
ax.axvline(T_obs, color="black", linestyle="--", linewidth=1.5)
ax.text(T_obs - 0.3, ax.get_ylim()[1]*0.9, r"$T_{obs}=12$", ha="right")

ax.set_xlabel("T (Count Five statistic)")
ax.set_ylabel("proportion")
plt.tight_layout()
plt.show()