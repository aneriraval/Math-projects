n, alpha, sigma0_sq, m = 20, 0.05, 4, 10000
rej = np.empty(m)

for j in range(m):
    x = np.random.chisquare(df=2,size=n)
    V = (n - 1) * x.var(ddof=1) / sigma0_sq
    rej[j] = V > stats.chi2.ppf(1 - alpha, df=n - 1)

p_hat = rej.mean()
se_hat = np.sqrt(p_hat * (1 - p_hat) / m)
print(f"P value={p_hat}")
