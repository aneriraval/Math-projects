#Calculating Type I error rate
import numpy as np
from scipy import stats
mu_0 = 500
sigma=100
n=20
alpha=0.05
num_simulations=100000
np.random.seed(42)
df=n-1
t_crit=stats.t.ppf(1-alpha,df)
samples=np.random.normal(loc=mu_0,scale=sigma,size=(num_simulations,n))
x_bar =np.mean(samples,axis=1)
s=np.std(samples,axis=1,ddof=1)
t_star=(x_bar-mu_0)/(s/np.sqrt(n))
rejections=t_star>t_crit
empirical_type_i_error_rate=np.mean(rejections)
print(f"Empirical Type I Error Rate: {empirical_type_i_error_rate}")
print("Theoretical Alpha: 0.05")

#Checking for mean
import numpy as np
from scipy import stats

n, alpha, mu0, sigma, m = 20, 0.05, 500, 100, 10000
p_vals = np.empty(m)

for j in range(m):
    x = np.random.normal(mu0, sigma, n)
    tstat = (x.mean() - mu0) / (x.std(ddof=1) / np.sqrt(n))
    p_vals[j] = 1 - stats.t.cdf(tstat, df=n - 1)

p_hat = np.mean(p_vals < alpha)
se_hat = np.sqrt(p_hat * (1 - p_hat) / m)
print(f"p value = {p_hat}")
print(f"standard error ={se_hat}")

#Checking for variance
import numpy as np
from scipy import stats

n, alpha, sigma0_sq, m = 20, 0.05, 4, 10000
rej = np.empty(m)

for j in range(m):
    x = np.random.normal(0, np.sqrt(sigma0_sq), n)
    V = (n - 1) * x.var(ddof=1) / sigma0_sq
    rej[j] = V > stats.chi2.ppf(1 - alpha, df=n - 1)

p_hat = rej.mean()
se_hat = np.sqrt(p_hat * (1 - p_hat) / m)
print(f"P value={p_hat}")
print(f"Standard error ={se_hat}")

#Checking for variance with chisquare
import numpy as np
