#Finding function with minimum variance
import numpy as np
import matplotlib.pyplot as plt
import scipy.stats as stats
N=100_000
np.random.seed(42)
def g(x):
  return np.where((x>0)&(x<1),np.exp(-x)/(1+x**2),0.0)

exact_value= 0.524797141419702
x0=np.random.uniform(0,1,N)
h0=g(x0)/1.0
est0=np.mean(h0)
var0=np.var(h0)
x1=np.random.exponential(scale=1.0,size=N)
h1=np.where((x1>0)&(x1<1),1.0/(1+x1**2),0.0)
est1=np.mean(h1)
var1=np.var(h1,ddof=1)
x2 = np.random.standard_cauchy(N)
h2 = np.where((x2 > 0) & (x2 < 1), np.pi * np.exp(-x2), 0.0)
est2, var2 = np.mean(h2), np.var(h2, ddof=1)
u3 = np.random.uniform(0, 1, N)
x3 = -np.log(1 - u3 * (1 - np.exp(-1)))
h3 = (1 - np.exp(-1)) / (1 + x3**2)
est3, var3 = np.mean(h3), np.var(h3, ddof=1)
u4 = np.random.uniform(0, 1, N)
x4 = np.tan(u4 * np.pi / 4)
