#Finding the best function in a family of functions
import numpy as np
import matplotlib.pyplot as plt

# Parameters
n = 1000
lambdas = [1, 2, 3, 4]

standard_errors = []

# Same seed for reproducibility
np.random.seed(123)

for lam in lambdas:

    # Generate U ~ Uniform(0,1)
    U = np.random.uniform(0, 1, n)

    # Generate X
    X = 10 - (1 / lam) * np.log(U)

    # Importance sampling ratio
    ratio = (X / lam) * np.exp((lam - 1) * X - 10 * lam)

    # Standard error
    SE = np.std(ratio, ddof=1) / np.sqrt(n)

    standard_errors.append(SE)

# Print values
for lam, se in zip(lambdas, standard_errors):
    print(f"Lambda = {lam}, Standard Error = {se:.8f}")

# Plot
plt.figure(figsize=(8, 5))
plt.plot(lambdas, standard_errors, marker='o')

plt.xlabel("Lambda (λ)")
plt.ylabel("Standard Error")
plt.title("Standard Error vs Lambda")
plt.xticks(lambdas)
plt.grid(True)

plt.show()

